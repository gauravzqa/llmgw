@dataclass
class Measured:
    """Everything one live request taught us. Never carries a credential."""

    label: str
    workload: str
    model_id: str
    stream: bool
    status: int = 0
    ttft_ms: float | None = None
    """Time to the FIRST BYTE of the response body, not to the headers.

    The two are far apart on a real provider and identical on the fakes, which
    is exactly why `first_event` is its own budget: the status line arrives in
    milliseconds and the first token arrives when the model starts talking.
    """
    headers_ms: float | None = None
    total_ms: float = 0.0
    usage: Usage = field(default_factory=Usage)
    usd: float = 0.0
    gw: dict[str, str] = field(default_factory=dict)
    upstream_headers: dict[str, str] = field(default_factory=dict)
    events: list[str] = field(default_factory=list)
    """Every distinct SSE `event:` name (or synthetic tag) the stream carried.
    The list the fakes never produced is the finding."""
    error_body: str = ""
    note: str = ""

    @property
    def gw_line(self) -> str:
        keys = ("x-gw-attempts", "x-gw-served-by", "x-gw-workload-id",
                "x-gw-body-modified")
        return " ".join(f"{k.removeprefix('x-gw-')}={self.gw[k]}"
                        for k in keys if k in self.gw)


def usd_of(usage: Usage, model: ModelSpec) -> float:
    """Measured cost, from the catalog the gateway itself prices with.

    Cache reads are priced through `price_of(cached=True)`, which falls back to
    the full input rate when a model does not support caching -- the fallback
    that must not be zero, or every uncached provider looks free.
    """
    write_rate = (model.cache_write_per_m if model.cache_write_per_m is not None
                  else model.input_per_m)
    return (
        usage.input_tokens * model.input_per_m
        + usage.cache_read_tokens * price_of(model, cached=True)
        + usage.cache_write_tokens * write_rate
        + usage.output_tokens * model.output_per_m
    ) / 1_000_000


def measure(
    gw: GatewayServer, workload: str, *, stream: bool, catalog: Catalog,
    model_id: str, label: str | None = None, timeout: float = 90.0,
) -> Measured:
    """Send one request through the gateway and account for it honestly."""
    surface = WORKLOAD_SURFACE[workload]
    route = f"/workloads/{workload}{ROUTE_FOR[surface.name]}"
    body = body_for(surface, stream=stream)
    out = Measured(label=label or f"{workload}/{'stream' if stream else 'json'}",
                   workload=workload, model_id=model_id, stream=stream)
    model = catalog.models[model_id]
    started = time.perf_counter()
    with httpx.Client(timeout=httpx.Timeout(timeout, connect=10.0)) as client:
        if not stream:
            resp = client.post(gw.base_url + route, json=body)
            out.headers_ms = out.ttft_ms = (time.perf_counter() - started) * 1000
            out.total_ms = out.ttft_ms
            out.status = resp.status_code
            out.gw = {k: v for k, v in resp.headers.items() if k.startswith("x-gw-")}
            out.upstream_headers = _interesting(resp.headers)
            if resp.status_code == 200:
                _usage_from_json(resp.content, out.usage)
            else:
                out.error_body = resp.text[:400]
            out.usd = usd_of(out.usage, model)
            return out

        parser = SSEParser(max_frame_bytes=1 << 20)
        seen: list[str] = []
        with client.stream("POST", gw.base_url + route, json=body) as resp:
            out.headers_ms = (time.perf_counter() - started) * 1000
            out.status = resp.status_code
            out.gw = {k: v for k, v in resp.headers.items() if k.startswith("x-gw-")}
            out.upstream_headers = _interesting(resp.headers)
            if resp.status_code != 200:
                out.error_body = resp.read().decode("utf-8", "replace")[:400]
                out.total_ms = (time.perf_counter() - started) * 1000
                return out
            body_bytes = 0
            try:
                for chunk in resp.iter_raw():
                    if out.ttft_ms is None and chunk:
                        out.ttft_ms = (time.perf_counter() - started) * 1000
                    body_bytes += len(chunk)
                    if body_bytes == len(chunk) and chunk[:2] == b"\x1f\x8b":
                        out.note = ("first two body bytes are 1f 8b -- this is a "
                                    "GZIP MEMBER, not SSE text")
                    for ev in parser.feed(chunk):
                        _note_event(ev, seen)
                        surface.apply_usage(ev, out.usage)
                for ev in parser.close():
                    _note_event(ev, seen)
                    surface.apply_usage(ev, out.usage)
            except httpx.RemoteProtocolError as exc:
                # C2 in the wild: a post-commitment failure ends the body with
                # no chunked terminator, and the client's own HTTP stack -- not
                # ours -- raises. Recorded rather than re-raised, because the
                # truncation IS the observation.
                out.note = (out.note + " | " if out.note else "") + (
                    f"TRUNCATED after {body_bytes} B: {type(exc).__name__}: {exc}"
                )
        out.total_ms = (time.perf_counter() - started) * 1000
    out.events = seen
    out.usd = usd_of(out.usage, model)
    return out


def _note_event(ev: Any, seen: list[str]) -> None:
    if ev.is_comment:
        tag = "<sse-comment>"
    elif ev.event:
        tag = ev.event
    elif ev.data.strip() == b"[DONE]":
        tag = "[DONE]"
    else:
        tag = "<unnamed-data>"
    if tag not in seen:
        seen.append(tag)


def _usage_from_json(body: bytes, usage: Usage) -> None:
    """Non-streaming usage. Read here rather than by a surface on purpose:
    `Surface.apply_usage` takes an SSE frame, and the buffered path has none."""
    try:
        parsed = json.loads(body)
    except ValueError:
        usage.parse_failures += 1
        return
    u = parsed.get("usage") or {}
    if "input_tokens" in u:  # Anthropic: disjoint already
        usage.input_tokens = int(u.get("input_tokens") or 0)
        usage.cache_read_tokens = int(u.get("cache_read_input_tokens") or 0)
        usage.cache_write_tokens = int(u.get("cache_creation_input_tokens") or 0)
    else:  # OpenAI: prompt_tokens INCLUDES cached_tokens, so subtract
        cached = int(((u.get("prompt_tokens_details") or {}).get("cached_tokens")) or 0)
        usage.input_tokens = max(0, int(u.get("prompt_tokens") or 0) - cached)
        usage.cache_read_tokens = cached
    usage.output_tokens = int(u.get("output_tokens") or u.get("completion_tokens") or 0)
    usage.input_exact = usage.output_exact = True


INTERESTING_PREFIXES = (
    "anthropic-", "x-request-id", "request-id", "openai-", "x-ratelimit",
    "retry-after", "x-openrouter", "cf-ray", "server", "x-envoy",
)


def _interesting(headers: httpx.Headers) -> dict[str, str]:
    """Response headers the fakes never sent. Forwarded ones only -- the
    gateway's allowlist decides what a client can see, and what survives it
    is itself a finding."""
    return {
        k: v for k, v in headers.items()
        if any(k.startswith(p) for p in INTERESTING_PREFIXES)
    }


