def body_for(surface: Surface, *, stream: bool) -> dict[str, Any]:
    body: dict[str, Any] = {
        # Overwritten on the wire by `upstream.apply_api_model`; sent because
        # both dialects require the field and because a body that omits it is
        # a body we would be testing a different code path with.
        "model": "placeholder",
        "max_tokens": MAX_TOKENS,
        "messages": [{"role": "user", "content": PROMPT}],
        "stream": stream,
    }
    if stream and surface is OPENAI_CHAT:
        # Without this, an OpenAI-dialect stream carries NO usage frame and
        # every streamed request is billed by estimate. Anthropic always
        # reports; OpenAI-shaped providers only report when asked.
        body["stream_options"] = {"include_usage": True}
    return body


