def raw_request(gw: GatewayServer, route: str, body: dict[str, Any],
                *, timeout: float = 90.0) -> bytes:
    """Speak HTTP/1.1 by hand and return every byte the client received.

    `httpx` parses the response and hands back one object, which cannot
    distinguish "one status line" from "one status line that a second one
    replaced". Counting `HTTP/1.1 ` occurrences in the raw octets is the only
    honest form of the C1 assertion, and a fallback is exactly the case where
    a broken gateway would emit two.
    """
    payload = json.dumps(body).encode()
    request = (
        f"POST {route} HTTP/1.1\r\nHost: 127.0.0.1:{gw.port}\r\n"
        f"Content-Type: application/json\r\nContent-Length: {len(payload)}\r\n"
        f"Accept: text/event-stream\r\nConnection: close\r\n\r\n"
    ).encode() + payload
    sock = socket.create_connection(("127.0.0.1", gw.port), timeout=timeout)
    sock.settimeout(timeout)
    try:
        sock.sendall(request)
        buf = bytearray()
        while True:
            chunk = sock.recv(65536)
            if not chunk:
                break
            buf += chunk
        return bytes(buf)
    finally:
        sock.close()


def status_lines(raw: bytes) -> list[str]:
    return [
        line.decode("latin-1")
        for line in raw.split(b"\r\n")
        if line.startswith(b"HTTP/1.")
    ]


