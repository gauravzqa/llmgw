@dataclass
class GatewayServer:
    app: Starlette
    server: uvicorn.Server
    thread: threading.Thread
    port: int

    @property
    def base_url(self) -> str:
        return f"http://127.0.0.1:{self.port}"

    def stop(self, timeout: float = 10.0) -> None:
        self.server.should_exit = True
        self.thread.join(timeout)
        if self.thread.is_alive():  # pragma: no cover
            self.server.force_exit = True
            self.thread.join(timeout)


def serve(app: Starlette, *, startup_timeout: float = 15.0) -> GatewayServer:
    """uvicorn on its own thread with `lifespan="on"`.

    `lifespan="on"` is not optional: the upstream pool is created in the
    Starlette lifespan so that it can be CLOSED at shutdown, and a server
    started without it answers every request with a 500.
    """
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    sock.bind(("127.0.0.1", 0))
    sock.listen(64)
    port = sock.getsockname()[1]
    server = uvicorn.Server(
        uvicorn.Config(app, log_level="error", access_log=False, lifespan="on")
    )
    thread = threading.Thread(target=server.run, kwargs={"sockets": [sock]},
                              daemon=True, name=f"llmgw-live-{port}")
    thread.start()
    deadline = time.monotonic() + startup_timeout
    while not server.started:
        if not thread.is_alive() or time.monotonic() > deadline:  # pragma: no cover
            raise RuntimeError("gateway failed to start")
        time.sleep(0.005)
    return GatewayServer(app=app, server=server, thread=thread, port=port)


def build_live_app(policy_path: str, **overrides: Any) -> Starlette:
    """`build_app` with real providers. The ONE line that matters is
    `fake_upstreams=False`, and it is the default -- see `ServerConfig`."""
    settings: dict[str, Any] = {
        "catalog": live_catalog(),
        "fake_upstreams": False,
        "policy_file": policy_path,
        "budgets": Budgets(total=90.0, connect=5.0, first_event=30.0,
                           progress=20.0, client_stall=30.0),
    }
    settings.update(overrides)
    return build_app(ServerConfig(**settings).validated())


