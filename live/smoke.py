def run(*, spend: bool = True, out=sys.stdout) -> list[Measured]:
    catalog = live_catalog()
    results: list[Measured] = []
    with tempfile.TemporaryDirectory(prefix="llmgw-live-") as tmp:
        policy = Path(tmp) / "live.toml"
        policy.write_text(POLICY_TOML, encoding="utf-8")
        gw = serve(build_live_app(str(policy)))
        try:
            print(f"gateway on {gw.base_url}  fake_upstreams=False", file=out)
            for wl in FALLBACK_WORKLOADS:
                probe = httpx.get(f"{gw.base_url}/workloads/{wl}/probe",
                                  timeout=10).json()
                print(f"  probe /workloads/{wl}: "
                      f"targets={[t['served_by'] for t in probe['targets']]} "
                      f"upstream_called={probe['upstream_called']}", file=out)

            if not spend:
                return results

            for wl in STREAM_WORKLOADS:
                results.append(measure(gw, wl, stream=True, catalog=catalog,
                                       model_id=MODEL_OF[wl]))
            for wl in ("anthropic", "anthropic-identity"):
                results.append(measure(
                    gw, wl, stream=False, catalog=catalog, model_id=MODEL_OF[wl],
                    label=f"{wl}/non-streaming"))

            echo_roundtrip(gw, out=out)
            usage_fields_case(gw, out=out)
            cache_write_read_case(gw, out=out)
            big_vision_case(gw, out=out)
            # Phase C5: the shapes the sweeps found untested, and the new routes.
            anthropic_tool_roundtrip_case(gw, out=out)
            anthropic_vision_and_pdf_case(gw, out=out)
            anthropic_structured_and_adaptive_case(gw, out=out)
            openai_parallel_tools_case(gw, out=out)
            phase_c_routes_case(gw, out=out)

            # ---- Task 3: fallback across two real providers, raw socket ----
            for wl in FALLBACK_WORKLOADS:
                surface = WORKLOAD_SURFACE[wl]
                route = f"/workloads/{wl}{ROUTE_FOR[surface.name]}"
                started = time.perf_counter()
                raw = raw_request(gw, route, body_for(surface, stream=True))
                elapsed = (time.perf_counter() - started) * 1000
                results.append(_measure_from_raw(raw, catalog, elapsed, wl))
        finally:
            gw.stop()
    render(results, out=out)
    return results


def _measure_from_raw(raw: bytes, catalog: Catalog, elapsed_ms: float,
                      workload: str = "fallback") -> Measured:
    lines = status_lines(raw)
    head, _, body = raw.partition(b"\r\n\r\n")
    headers = {}
    for line in head.split(b"\r\n")[1:]:
        name, _, value = line.partition(b":")
        headers[name.decode("latin-1").lower().strip()] = value.decode("latin-1").strip()
    out = Measured(label=f"{workload}/raw-socket", workload=workload,
                   model_id=MODEL_OF[workload], stream=True)
    out.status = int(lines[0].split()[1]) if lines else 0
    out.total_ms = elapsed_ms
    out.gw = {k: v for k, v in headers.items() if k.startswith("x-gw-")}
    out.upstream_headers = {k: v for k, v in headers.items()
                            if any(k.startswith(p) for p in INTERESTING_PREFIXES)}
    out.note = f"status lines on the wire: {len(lines)} ({', '.join(lines)})"
    parser = SSEParser(max_frame_bytes=1 << 20)
    seen: list[str] = []
    payload = _dechunk(body) if headers.get("transfer-encoding") == "chunked" else body
    for ev in parser.feed(payload) + parser.close():
        _note_event(ev, seen)
        OPENAI_CHAT.apply_usage(ev, out.usage)
    out.events = seen
    out.usd = usd_of(out.usage, catalog.models[out.model_id])
    return out


def _dechunk(body: bytes) -> bytes:
    """HTTP/1.1 chunked decoding, because we asked for the raw octets.

    Reading a streamed body without this is how you end up asserting against
    hex chunk sizes interleaved with SSE frames and concluding the framing is
    broken.
    """
    out = bytearray()
    rest = body
    while True:
        line, sep, rest = rest.partition(b"\r\n")
        if not sep:
            break
        try:
            size = int(line.split(b";")[0] or b"0", 16)
        except ValueError:
            break
        if size == 0:
            break
        out += rest[:size]
        rest = rest[size + 2:]
    return bytes(out)


def render(results: list[Measured], out=sys.stdout) -> None:
    print("", file=out)
    print("=" * 78, file=out)
    print("LIVE SMOKE -- real providers, real TLS, real latency", file=out)
    print("=" * 78, file=out)
    total = 0.0
    for r in results:
        total += r.usd
        print(f"\n{r.label}  [{r.model_id}]", file=out)
        print(f"  HTTP {r.status}   headers {_ms(r.headers_ms)}   "
              f"first byte {_ms(r.ttft_ms)}   total {_ms(r.total_ms)}", file=out)
        u = r.usage
        print(f"  tokens in={u.input_tokens} out={u.output_tokens} "
              f"cache_read={u.cache_read_tokens} cache_write={u.cache_write_tokens} "
              f"exact={u.exact} (in={u.input_exact} out={u.output_exact})", file=out)
        print(f"  USD {r.usd:.8f}", file=out)
        if r.gw:
            print(f"  X-Gw: {r.gw_line}", file=out)
            print(f"        policy={r.gw.get('x-gw-policy-id', '-')} "
                  f"catalog={r.gw.get('x-gw-catalog-id', '-')}", file=out)
        if r.events:
            print(f"  SSE events: {', '.join(r.events)}", file=out)
        if r.upstream_headers:
            print(f"  forwarded upstream headers: "
                  f"{json.dumps(r.upstream_headers)[:300]}", file=out)
        if r.note:
            print(f"  {r.note}", file=out)
        if r.error_body:
            print(f"  error body: {r.error_body}", file=out)
    print("", file=out)
    print(f"TOTAL MEASURED SPEND: ${total:.8f} over {len(results)} requests", file=out)


def _ms(value: float | None) -> str:
    return "-" if value is None else f"{value:8.1f} ms"


